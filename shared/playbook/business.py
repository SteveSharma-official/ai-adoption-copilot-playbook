def tenant_baseline(licences_csv, usage_csv, agents_csv) -> tuple[Result, str]:
    """Summarise exports taken from a tenant (or the synthetic samples) into 'what did we buy'."""
    r = Result("1.2", "Tenant baseline: what did we buy?")
    lic = load(licences_csv); usage = load(usage_csv); agents = load(agents_csv)
    copilot = [x for x in lic if "COPILOT" in x["sku_part_number"].upper()]
    assigned = sum(int(x["consumed_units"]) for x in copilot)
    purchased = sum(int(x["enabled_units"]) for x in copilot)
    active = [u for u in usage if u.get("last_activity_date")]
    r.data = {"copilot_seats_purchased": purchased, "copilot_seats_assigned": assigned,
              "users_with_any_copilot_activity_30d": len(active), "agents_in_export": len(agents),
              "agents_without_owner": sum(1 for a in agents if not a.get("owner"))}
    if purchased and assigned / purchased < 0.8:
        r.find("unassigned-seats", f"{purchased - assigned} purchased Copilot seats are unassigned.", blocking=False)
    if r.data["agents_without_owner"]:
        r.find("agents-without-owner", f"{r.data['agents_without_owner']} agents in the export have no recorded owner.", blocking=False)
    md = "# Tenant Baseline\n\n" + md_table([{"measure": k, "value": v} for k, v in r.data.items()], ["measure", "value"]) + \
         "\nActivity counts show that people used Copilot. They do not show business value (see Chapter 3).\n"
    return r, md


