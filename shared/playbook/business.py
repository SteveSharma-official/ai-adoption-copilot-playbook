RUNGS = ["Buy", "Configure", "Integrate", "Build", "Host"]
SURFACE = {"Buy": "Microsoft 365 Copilot", "Configure": "Agent Builder or Copilot Studio (declarative agent)",
           "Integrate": "Copilot Studio with connectors, tools and agent flows",
           "Build": "Microsoft Foundry or Microsoft 365 Agents SDK", "Host": "Self-hosted or sovereign model (outside this book)"}


def minimum_rung(w) -> str:
    if w.get("must_stay_in_boundary_beyond_service") and w.get("classification") in ("secret", "top_secret"):
        return "Host"
    if w.get("needs_custom_model") or w.get("needs_multi_model_orchestration"):
        return "Build"
    if w.get("needs_system_actions") or w.get("needs_external_data"):
        return "Integrate"
    if w.get("needs_custom_instructions_or_knowledge"):
        return "Configure"
    return "Buy"


def decision_ladder(workloads_yaml) -> tuple[Result, str]:
    r = Result("4.1", "Workload-to-platform decision ladder")
    rows = []
    for w in load(workloads_yaml)["workloads"]:
        need = minimum_rung(w); prop = w.get("proposed_rung", need)
        rows.append({"workload": w["name"], "minimum_rung": need, "proposed_rung": prop, "surface": SURFACE[prop]})
        if RUNGS.index(prop) > RUNGS.index(need) and not w.get("lower_rung_disproven"):
            r.find("unjustified-climb", f"'{w['name']}' proposed at {prop} but {need} meets the stated requirements; record why the lower rung fails.", workload=w["name"])
        if RUNGS.index(prop) < RUNGS.index(need):
            r.find("under-scoped", f"'{w['name']}' proposed at {prop} cannot meet requirements that need {need}.", workload=w["name"])
        if prop in ("Integrate", "Build") and (w.get("serves_unlicensed_users") or w.get("runs_autonomously")):
            r.find("consumption-cost", f"'{w['name']}' will consume Copilot Credits or Foundry spend; model it before approval.", blocking=False)
    r.data = {"decisions": rows}
    return r, "# Decision Ladder\n\n" + md_table(rows, ["workload", "minimum_rung", "proposed_rung", "surface"])
