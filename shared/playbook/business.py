ZONES = ["Microsoft 365 Copilot", "Copilot Studio", "Microsoft Foundry", "Platform where the data lives"]


def place_workload(w) -> tuple[str, str]:
    data_in_m365 = w["data_boundary"] == "m365"
    acts = w["action_autonomy"] in ("acts", "acts_with_approval")
    deep = w["integration_depth"] in ("custom_model", "multi_system_orchestration")
    if not data_in_m365 and w.get("data_volume") == "large":
        return ZONES[3], "Large data set outside Microsoft 365: move the AI to the data, not the data to the AI."
    if deep:
        return ZONES[2], "Needs model choice or multi-system orchestration beyond declarative agents."
    if acts or not data_in_m365:
        return ZONES[1], "Needs actions or connectors to systems outside Microsoft 365, with approval gates."
    return ZONES[0], "Assistive work over Microsoft 365 content the user can already access."


def portfolio(sanctioned_csv, proxy_csv, workloads_yaml) -> tuple[Result, str]:
    r = Result("2.1", "Enterprise AI portfolio map and workload placement")
    sanctioned = {x["domain"] for x in load(sanctioned_csv)}
    proxy = load(proxy_csv)
    ai = [p for p in proxy if p["category"].startswith("ai_")]
    shadow = {}
    for p in ai:
        if p["domain"] not in sanctioned:
            s = shadow.setdefault(p["domain"], {"domain": p["domain"], "departments": set(), "requests_30d": 0, "upload_mb_30d": 0.0})
            s["departments"].add(p["department"]); s["requests_30d"] += int(p["requests_30d"])
            s["upload_mb_30d"] += int(p["upload_bytes_30d"]) / 1e6
    shadow_rows = [dict(v, departments=", ".join(sorted(v["departments"])), upload_mb_30d=round(v["upload_mb_30d"], 1)) for v in shadow.values()]
    wl = load(workloads_yaml)["workloads"]
    placements = []
    for w in wl:
        zone, why = place_workload(w)
        row = {"workload": w["name"], "recommended": zone, "proposed": w.get("proposed_platform", ""), "rationale": why}
        placements.append(row)
        if w.get("proposed_platform") and w["proposed_platform"] != zone:
            if not w.get("approved_exception"):
                r.find("forced-fit", f"'{w['name']}' proposed on {w['proposed_platform']} but placement recommends {zone}.", workload=w["name"])
            else:
                r.find("approved-exception", f"'{w['name']}' placed on {w['proposed_platform']} under exception: {w['approved_exception']}", blocking=False)
    for s in shadow_rows:
        r.find("shadow-ai", f"Unsanctioned AI service {s['domain']} used by {s['departments']} ({s['upload_mb_30d']} MB uploaded in 30 days).", blocking=False)
    r.data = {"shadow_ai": shadow_rows, "placements": placements}
    md = "# Enterprise AI Portfolio Map\n\n## Shadow AI signals (synthetic proxy summary)\n\n" + \
         md_table(shadow_rows, ["domain", "departments", "requests_30d", "upload_mb_30d"]) + \
         "\nTreat these as demand signals, not disciplinary findings.\n\n## Workload placement\n\n" + \
         md_table(placements, ["workload", "proposed", "recommended", "rationale"])
    return r, md


# ------------------------------------------------------------------ Lab 3.1
def _durations(events):
    by_case = {}
    for e in events:
        by_case.setdefault(e["case_id"], {})[e["step"]] = parse_ts(e["timestamp"])
    steps = ["received", "triaged", "data_lookup_done", "draft_done", "approved", "closed"]
    per_step = {s: [] for s in steps[1:]}
    total = []
    for c in by_case.values():
        if not all(s in c for s in steps):
            continue
        for a, b in zip(steps, steps[1:]):
            per_step[b].append((c[b] - c[a]).total_seconds() / 3600)
        total.append((c["closed"] - c["received"]).total_seconds() / 3600)
    return per_step, total


def value_baseline(events_csv, hypothesis_yaml) -> tuple[Result, str]:
    r = Result("3.1", "Value hypothesis and baseline")
    ev = load(events_csv); h = load(hypothesis_yaml)
    base = [e for e in ev if e["period"] == "baseline"]; pilot = [e for e in ev if e["period"] == "pilot"]
    bs, bt = _durations(base); ps, pt = _durations(pilot)
    med = lambda xs: round(statistics.median(xs), 2) if xs else None
    rows = [{"step": s, "baseline_median_h": med(bs[s]), "pilot_median_h": med(ps[s])} for s in bs]
    bottleneck = max(bs, key=lambda s: statistics.median(bs[s]))
    total_b, total_p = med(bt), med(pt)
    change_total = (total_b - total_p) / total_b if total_b else 0
    target = h["target_step"]
    change_target = (med(bs[target]) - med(ps[target])) / med(bs[target])
    r.data = {"steps": rows, "bottleneck_step": bottleneck, "total_baseline_median_h": total_b, "total_pilot_median_h": total_p,
              "total_change_pct": round(100 * change_total, 1), "target_step": target, "target_change_pct": round(100 * change_target, 1),
              "cases_baseline": len(bt), "cases_pilot": len(pt)}
    if min(len(bt), len(pt)) < int(h.get("minimum_cases", 30)):
        r.find("insufficient-sample", f"Need at least {h.get('minimum_cases', 30)} complete cases in each period.")
    if target != bottleneck:
        r.find("not-the-bottleneck", f"Hypothesis targets '{target}' but the measured bottleneck is '{bottleneck}'.")
    if change_target > 0.2 and change_total < float(h.get("expected_total_reduction", 0.2)):
        r.find("efficiency-trap", f"'{target}' improved {round(100*change_target)}% but total cycle time moved only {round(100*change_total)}%.")
    if change_total < float(h.get("expected_total_reduction", 0.2)):
        r.find("hypothesis-not-supported", f"Total cycle time fell {round(100*change_total,1)}%; hypothesis expected {round(100*float(h['expected_total_reduction']))}%.")
    md = f"# Value Baseline: {h.get('process')}\n\n**Hypothesis:** {h.get('statement')}\n\n" + \
         md_table(rows, ["step", "baseline_median_h", "pilot_median_h"]) + \
         f"\nMeasured bottleneck: **{bottleneck}**. Total median cycle time: {total_b} h baseline, {total_p} h pilot " \
         f"({r.data['total_change_pct']}% change, {len(bt)} and {len(pt)} cases).\n\n" \
         "_Synthetic lab data. Medians are used because cycle times are skewed; report the sample size with every figure._\n"
    return r, md


