# Copilot Enterprise Adoption Model: the gate evidence required to *claim* each level.
LEVEL_GATES = {
    1: [],
    2: ["value_hypothesis", "baseline_signed", "business_owner"],
    3: ["exposure_report_signed", "agents_have_identity_and_owner"],
    4: ["production_readiness_gate_passed"],
    5: ["shared_platform_foundation", "portfolio_process"],
}
LEVEL_NAMES = {1: "Experiment", 2: "Controlled pilot", 3: "Operational", 4: "Scaled", 5: "Agentic enterprise"}


def adoption_assessment(assessment_path, lab_dir) -> tuple[Result, str]:
    a = load(assessment_path)
    r = Result("1.1", "Copilot Enterprise Adoption Model self-assessment")
    evidence = a.get("evidence", {})
    def present(gate):
        ref = evidence.get(gate)
        return bool(ref) and (Path(lab_dir) / ref).exists()
    evidenced = 1
    missing_for_next = []
    for lvl in range(2, 6):
        gates = LEVEL_GATES[lvl]
        miss = [g for g in gates if not present(g)]
        if miss:
            missing_for_next = miss
            break
        evidenced = lvl
    claimed = int(a.get("claimed_level", 1))
    r.data = {"organisation": a.get("organisation"), "claimed_level": claimed, "evidenced_level": evidenced,
              "next_level_missing_evidence": missing_for_next, "decision_requested": a.get("decision_requested")}
    if claimed > evidenced:
        r.find("claimed-level-unsupported",
               f"Claimed Level {claimed} ({LEVEL_NAMES[claimed]}) but evidence supports Level {evidenced} ({LEVEL_NAMES[evidenced]}).",
               missing=missing_for_next)
    if a.get("decision_requested") not in ("strategic standard", "one platform among several", "restricted tool"):
        r.find("decision-not-framed", "decision_requested must be one of: strategic standard, one platform among several, restricted tool.")
    md = [f"# Platform Fit One-Pager: {a.get('organisation')}", "",
          f"**Decision requested:** {a.get('decision_requested')}", "",
          f"**Where we honestly are:** Level {evidenced} ({LEVEL_NAMES[evidenced]}) on the Copilot Enterprise Adoption Model.",
          f"**Level claimed by the programme:** Level {claimed}.", "",
          f"**Value hypothesis:** {a.get('value_hypothesis_summary', 'not yet written')}",
          f"**Exposure position:** {a.get('exposure_summary', 'not yet measured')}",
          f"**Agent position:** {a.get('agent_summary', 'not yet inventoried')}",
          f"**Cost including consumption:** {a.get('cost_summary', 'not yet modelled')}", "",
          "**Condition for moving up:** provide evidence for " + (", ".join(missing_for_next) or "nothing further: top level evidenced"), "",
          "_Generated by Lab 1.1. Every statement above must trace to a file in the evidence map._"]
    return r, "\n".join(md)


